//! The build half of LMDB's runtime route: four modules and two generated
//! files.
//!
//! An SDK that ships the runtime route calls `createModule` in place of
//! `translate.createModule()` and imports what comes back as its `c` module.
//! Nothing here links liblmdb. That is the point: in this configuration the
//! `mdb_*` entry points arrive through the platform loader at run time, and
//! linking the archive as well would make the linker resolve those symbols
//! before `load` ever ran — the runtime route would silently be a linked one.
//!
//!   rt        runtime/loader.zig, the reusable core. Pure Zig; imported by the
//!             facade in a linked build, because `LoadSource` and `LoadError`
//!             are this SDK's public types and must be the same types in both
//!             configurations.
//!   library   runtime/library.zig, this SDK's descriptor: the namespaced
//!             synchronization binding, the ABI record and the one load-time
//!             check.
//!   dispatch  generated by runtime/generate.zig from the real translation
//!             output: the table, one wrapper per entry point, the live address
//!             accessor per exported datum, `load`, and the re-exported
//!             translated namespace. It imports `rt`, `library` and the
//!             patched translation as `c_native`.
//!   native    the generator's second file: the same translation with the
//!             `__root` prologue Aro writes replaced by an import of the
//!             dispatch as `c_routed`, so a declaration nested inside a
//!             translated type names the routed wrapper rather than the raw
//!             extern. It imports the dispatch and nothing else.
//!   sync.c    compiled into the dispatch with `-DRT_SYNC_PREFIX=lmdb_rt`, so
//!             its symbols cannot collide with another SDK's.
//!
//! ## The one thing a caller must not do
//!
//! Do not link the compiled C archive into a module that imports this
//! dispatch. The facade's `c` import is the dispatch, and nothing else in the
//! graph may reference liblmdb, or the linker satisfies the same `mdb_*` names
//! statically and the runtime route becomes a linked one.
//!
//! ## Which provider this accepts
//!
//! Any liblmdb shared object built from the header named here — this
//! repository's `libraries/liblmdb/lmdb.h` at the default setting, or the
//! installed header when the translation was `-fsys=lmdb` — as long as it
//! exports every `mdb_*` function that header declares. `runtime/library.zig`
//! states the external family, the configuration macros that fix layouts, and
//! the allocator boundary; read it before choosing a provider, because a
//! resolved symbol is not an ABI match.

const std = @import("std");

/// The prefix `runtime/sync.c` is compiled with.
///
/// `runtime/library.zig` declares the same prefix in the symbol names it binds.
/// The two must agree, and a build where they do not fails to link, which is
/// the whole error report: there is no runtime path that could hide it.
///
/// A build that needs a second, independent instance of this SDK in one binary
/// should change this value *and* the prefix in `runtime/library.zig`, and then
/// give the second instance its own copy of both files. Nothing else in the
/// package assumes one instance.
const sync_prefix = "lmdb_rt";

/// `extern` declarations that the C library provides and that must therefore
/// stay direct.
///
/// `libraries/liblmdb/lmdb.h` includes `<sys/types.h>`, `<inttypes.h>` and
/// `<limits.h>` (lmdb.h:171-173), so what this build hands the translator is a
/// preprocessed translation unit (`build.zig`, `preprocessedHeader`) carrying
/// those headers' declarations alongside LMDB's. They are the C library's, not
/// liblmdb's: a liblmdb shared object exports the `mdb_*` names and not
/// `memcpy`, so a routed lookup for one of them would fail a load that has
/// nothing wrong with the provider. Names that this particular target's headers
/// do not surface are simply never matched, which is why the list can be wider
/// than any single translation. It is, deliberately: on 2026-10-04 the pinned
/// translator was run over this SDK's preprocessed aggregate for all 53
/// published cross-test targets and the six check targets, and the union of
/// the C-library `extern` declarations it emitted adds eleven names this list
/// did not have — `imaxabs`, `imaxdiv`, `strtoimax`, `strtoumax`, `wcstoimax`
/// and `wcstoumax` from `<inttypes.h>`, `select` and `pselect` from
/// `<sys/select.h>`, `__darwin_check_fd_set_overflow` from
/// `any-darwin-any/sys/_types/_fd_def.h:54`, and MinGW's
/// `__mingw_get_crt_info` (`any-windows-any/_mingw.h:665`) and `__prefetch`
/// (`any-windows-any/_mingw.h:650`).
///
/// Every name here is a C library function. None begins with `mdb_`, so the
/// list cannot de-route a native symbol. The authoritative record of what *was*
/// routed is the `symbols` array in the generated dispatch.
const libc_noise =
    \\memcpy,memmove,memset,memcmp,memchr,memrchr,
    \\strlen,strcmp,strncmp,strcpy,strncpy,strcasecmp,strncasecmp,strchr,strrchr,
    \\strstr,strdup,strndup,strerror,strtok,strspn,strcspn,strpbrk,strcoll,strxfrm,
    \\malloc,calloc,realloc,reallocarray,free,aligned_alloc,posix_memalign,
    \\abort,exit,_exit,_Exit,atexit,atexit_quick,
    \\snprintf,vsnprintf,sprintf,vsprintf,printf,vprintf,fprintf,vfprintf,
    \\fputs,fputc,putchar,puts,putc,putchar_unlocked,fflush,fclose,fopen,fread,
    \\fwrite,freopen,perror,fseek,ftell,fseeko,ftello,
    \\open,openat,close,read,write,pread,pwrite,preadv,pwritev,lseek,llseek,
    \\ftruncate,fsync,fdatasync,msync,fstat,stat,lstat,fstatat,unlink,rename,
    \\access,chmod,fchmod,mkdir,rmdir,truncate,
    \\mmap,munmap,mprotect,getpagesize,
    \\getenv,setenv,unsetenv,clearenv,putenv,system,
    \\time,clock,gettimeofday,difftime,localtime,gmtime,mktime,strftime,
    \\isprint,isalnum,isalpha,isdigit,isspace,isxdigit,toupper,tolower,
    \\qsort,bsearch,atoi,atol,strtol,strtoul,strtoll,strtoull,strtod,strtof,
    \\abs,labs,div,
    \\signal,raise,sigaction,
    \\dlopen,dlsym,dlclose,dlerror,dlvsym,
    \\pthread_mutex_init,pthread_mutex_lock,pthread_mutex_unlock,pthread_mutex_destroy,
    \\pthread_cond_init,pthread_cond_wait,pthread_cond_signal,pthread_cond_destroy,
    \\pthread_create,pthread_join,pthread_self,pthread_exit,pthread_key_create,
    \\sem_init,sem_wait,sem_post,sem_destroy,sem_open,sem_close,
    \\VirtualAlloc,VirtualFree,CreateFileW,WriteFile,ReadFile,CloseHandle,
    \\CreateMutexW,OpenMutexA,WaitForSingleObject,ReleaseMutex,
    \\LockFileEx,UnlockFileEx,CreateEventW,SetEvent,GetFileSizeEx,
    \\imaxabs,imaxdiv,strtoimax,strtoumax,wcstoimax,wcstoumax,select,pselect,
    \\__darwin_check_fd_set_overflow,__mingw_get_crt_info,__prefetch,
;

/// `extern` declarations the provider may legitimately not export.
///
/// This SDK declares none, and the reason is in `libraries/liblmdb/lmdb.h`
/// rather than in a build flag. Every `mdb_*` function the header declares is
/// implemented by `mdb.c` unconditionally. The three that are *not* — 
/// `mdb_env_set_encrypt`, `mdb_env_set_checksum` and the callback typedefs they
/// take — sit inside `#if MDB_RPAGE_CACHE` (lmdb.h:317, :1096, :1118), and that
/// macro is defined to 1 by lmdb.h:192-195 itself unless `MDB_VL32` is
/// defined. This build passes no `-D` at all (`build.zig`, the `core` module),
/// so `MDB_VL32` is never defined, `MDB_RPAGE_CACHE` is 1, and the three are in
/// the translation and in the table.
///
/// The list is spelled out so that adding a header with an optional entry point
/// becomes a build-file change with a name in it rather than a load-time
/// mystery.
const provider_optional = "";

/// `extern` declarations this build does not require from a provider.
///
/// None. Every function `lmdb.h` declares for this target's configuration is
/// expected from a provider, and a provider that does not export one of them is
/// refused rather than half used.
///
/// The two compatibility aliases in the header, `mdb_open` and `mdb_close`
/// (lmdb.h:1303-1305), are *not* here and could not be: they are preprocessor
/// macros, not declarations, so they are not in the translated namespace in
/// either configuration and are not routed. In C they are `mdb_dbi_open` and
/// `mdb_dbi_close`, and those two are routed. A Zig caller naming `c.mdb_open`
/// finds nothing in a linked build either, so the dispatch does not remove a
/// name that was there.
///
/// A name here would be routed into a nullable table field instead: its absence
/// would not fail the load, and its wrapper would stop the program by name.
/// Only `libc_noise` above keeps a declaration direct.
const provider_excluded = "";

/// The loader core, for a *linked* build to import.
///
/// A linked build has no dispatch, so the facade needs the core module itself
/// for the two public types `LoadSource` and `LoadError`: they are this SDK's
/// types and they must be the same types a caller names in either
/// configuration. It costs a linked build two declarations and no code, since
/// nothing else in that module is referenced until a configuration actually
/// instantiates the loader.
///
/// A runtime-loading build must *not* import this separately: `createModule`
/// makes the one core instance the dispatch uses, and the dispatch re-exports
/// the two types from it. Two instances would be two sets of types, and a
/// consumer would be naming one while `load` expects the other.
pub fn createCoreModule(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    return b.createModule(.{
        .root_source_file = b.path("runtime/loader.zig"),
        .target = target,
        .optimize = optimize,
        // The Unix backend calls `dlopen`, which is libc. Nothing in this module
        // is compiled into a linked build, so this costs nothing there.
        .link_libc = true,
    });
}

/// The runtime-loaded `c` module for one target.
///
/// `translate` is the translation step for that same target and configuration;
/// its output is read by the generator, so the dispatch describes the header
/// this build actually selected rather than another one.
pub fn createModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    const core = createCoreModule(b, target, optimize);

    const library = b.createModule(.{
        .root_source_file = b.path("runtime/library.zig"),
        .target = target,
        .optimize = optimize,
    });
    library.addImport("rt", core);

    return createDispatchModule(b, translate, target, optimize, core, library);
}

/// What one generator run writes: the dispatch, and the translation it reads.
const GeneratedSources = struct {
    native: std.Build.LazyPath,
    dispatch: std.Build.LazyPath,
};

fn createDispatchModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    core: *std.Build.Module,
    library: *std.Build.Module,
) *std.Build.Module {
    const sources = generateDispatch(b, translate, target);

    const dispatch = b.createModule(.{
        .root_source_file = sources.dispatch,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    dispatch.addImport("rt", core);
    dispatch.addImport("library", library);

    // The patched translation, under a name that says what it is. Every type
    // and constant in the dispatch is re-exported from here rather than
    // restated, so `c.MDB_val` in a facade and `c_native.MDB_val` in the
    // dispatch are one nominal type, no call between them needs a cast, and
    // `c_routed` is what makes the members nested inside those types the
    // routed wrappers.
    const native = b.createModule(.{
        .root_source_file = sources.native,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    native.addImport("c_routed", dispatch);
    dispatch.addImport("c_native", native);
    dispatch.addCSourceFiles(.{
        .files = &.{"runtime/sync.c"},
        .flags = &.{b.fmt("-DRT_SYNC_PREFIX={s}", .{sync_prefix})},
        .language = .c,
    });
    return dispatch;
}

/// Runs the generator over the translation step's real output.
///
/// The generator is a host program built and run by this build, so the dispatch
/// is produced for the target being built from that target's own translation.
/// Nothing is cached across configurations: a different header configuration
/// produces a different translation step output, which produces a different
/// dispatch.
fn generateDispatch(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
) GeneratedSources {
    const generator = b.addExecutable(.{
        .name = b.fmt("lmdb-runtime-generate-{s}", .{
            target.result.zigTriple(b.allocator) catch @panic("unspellable target"),
        }),
        .root_module = b.createModule(.{
            .root_source_file = b.path("runtime/generate.zig"),
            .target = b.graph.host,
            .optimize = .Debug,
        }),
    });

    const run = b.addRunArtifact(generator);
    run.addArg("--library");
    run.addArg("lmdb");
    run.addArg("--translate");
    run.addFileArg(translate.getOutput());
    if (libc_noise.len != 0) {
        run.addArg("--noise");
        run.addArg(libc_noise);
    }
    if (provider_optional.len != 0) {
        run.addArg("--optional");
        run.addArg(provider_optional);
    }
    if (provider_excluded.len != 0) {
        run.addArg("--exclude");
        run.addArg(provider_excluded);
    }
    run.addArg("--native-output");
    const native_source = run.addOutputFileArg("native.zig");
    run.addArg("--output");
    const dispatch_source = run.addOutputFileArg("dispatch.zig");
    return .{ .native = native_source, .dispatch = dispatch_source };
}